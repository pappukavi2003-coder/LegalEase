"""Formatting & export helpers used by the Streamlit frontend to turn Gemini's
raw text into a clean preview and into downloadable .docx / .pdf files.
"""
from __future__ import annotations

import io
import re
from datetime import date

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Inches, Pt
from fpdf import FPDF
from fpdf.enums import XPos, YPos

from config import LOGO_PATH

_SMART_CHARS = {
    "\u2018": "'", "\u2019": "'", "\u201c": '"', "\u201d": '"',
    "\u2013": "-", "\u2014": "-", "\u2026": "...",
}
_CONTROL_CHARS = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f]")


def sanitize_text(text: str) -> str:
    """Normalize smart quotes/dashes and strip stray control characters."""
    if not text:
        return ""
    for bad, good in _SMART_CHARS.items():
        text = text.replace(bad, good)
    return _CONTROL_CHARS.sub("", text).strip()


def _terms_rows(terms: str) -> list[str]:
    return [t.strip() for t in terms.split(";") if t.strip()]


def format_docx(text: str, doc_type: str, terms: str = "") -> bytes:
    """Build a Word document with an optional logo, a title, the document body,
    a terms table, and a footer."""
    doc = Document()

    try:
        header = doc.sections[0].header
        hp = header.paragraphs[0]
        hp.alignment = WD_ALIGN_PARAGRAPH.CENTER
        hp.add_run().add_picture(LOGO_PATH, width=Inches(1.1))
    except Exception:
        pass  # a missing logo should never break the export

    title = doc.add_heading(doc_type.strip() or "Legal Document", level=1)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER

    for para in sanitize_text(text).split("\n"):
        stripped = para.strip()
        if not stripped:
            doc.add_paragraph("")
            continue
        if stripped.startswith("#"):
            doc.add_heading(stripped.lstrip("#").strip(), level=2)
            continue
        p = doc.add_paragraph(stripped)
        for run in p.runs:
            run.font.size = Pt(11)

    rows = _terms_rows(terms)
    if rows:
        doc.add_heading("Terms Summary", level=2)
        table = doc.add_table(rows=1, cols=1)
        table.style = "Light Grid Accent 1"
        table.rows[0].cells[0].text = "Term"
        for row_text in rows:
            table.add_row().cells[0].text = row_text

    footer_p = doc.add_paragraph()
    footer_run = footer_p.add_run(f"Generated by LegalEase on {date.today():%B %d, %Y}.")
    footer_run.italic = True
    footer_run.font.size = Pt(9)

    buffer = io.BytesIO()
    doc.save(buffer)
    return buffer.getvalue()


class _LegalPDF(FPDF):
    def header(self):
        try:
            self.image(LOGO_PATH, x=10, y=8, w=20)
        except Exception:
            pass
        self.set_font("Helvetica", "B", 14)
        self.ln(4)
        self.cell(0, 10, "LegalEase", align="C", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.ln(14)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.cell(0, 10, f"Page {self.page_no()} | Generated by LegalEase", align="C")


def format_pdf(text: str, doc_type: str) -> bytes:
    """Build a branded PDF with a header/logo, the document body, and a footer
    (page numbers) on every page."""
    pdf = _LegalPDF()
    pdf.set_auto_page_break(auto=True, margin=20)
    pdf.add_page()

    pdf.set_font("Helvetica", "B", 13)
    pdf.multi_cell(0, 8, doc_type.strip() or "Legal Document", align="C", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.ln(4)

    pdf.set_font("Helvetica", size=11)
    for para in sanitize_text(text).split("\n"):
        stripped = para.strip()
        if not stripped:
            pdf.ln(3)
            continue
        if stripped.startswith("#"):
            pdf.set_font("Helvetica", "B", 12)
            pdf.multi_cell(0, 7, stripped.lstrip("#").strip(), new_x=XPos.LMARGIN, new_y=YPos.NEXT)
            pdf.set_font("Helvetica", size=11)
            continue
        pdf.multi_cell(0, 6, stripped, new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    out = pdf.output(dest="S")
    return bytes(out) if not isinstance(out, (bytes, bytearray)) else bytes(out)


def format_html_preview(text: str) -> str:
    """Render the document as a dark, scrollable HTML card for the Streamlit preview."""
    safe = sanitize_text(text).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    body = []
    for para in safe.split("\n"):
        stripped = para.strip()
        if not stripped:
            body.append("<div style='height:8px;'></div>")
        elif stripped.startswith("#"):
            body.append(f"<h4 style='color:#f3f4f6;margin:14px 0 6px;'>{stripped.lstrip('# ').strip()}</h4>")
        else:
            body.append(f"<p style='margin:4px 0;color:#e5e7eb;'>{stripped}</p>")
    return (
        "<div style='background:#0f1420;padding:20px 24px;border-radius:10px;"
        "font-family:Georgia,\"Times New Roman\",serif;line-height:1.55;"
        "max-height:480px;overflow-y:auto;border:1px solid #2b3444;'>"
        + "".join(body)
        + "</div>"
    )
